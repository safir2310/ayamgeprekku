echo "------------------------------"
echo "Run this command:"
echo ""
echo -e "${GREEN}vercel link${NC}"
echo ""
echo "Follow the prompts to link to your project."
echo ""
read -p "Press Enter when project is linked..."

echo ""
echo -e "${BLUE}STEP 4: Add Environment Variables${NC}"
echo "------------------------------"
echo "Go to Vercel Dashboard:"
echo "  https://vercel.com/dashboard"
echo ""
echo "Then:"
echo "  1. Select your project"
