#!/bin/bash

# Manual Deployment Guide - Step by Step
# Gunakan ini jika deploy-vercel.sh tidak jalan

echo "🚀 Vercel Deployment - Manual Guide"
echo "===================================="
echo ""

# Color codes
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

